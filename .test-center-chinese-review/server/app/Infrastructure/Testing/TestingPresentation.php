        foreach(['scenario','workflow','dispatch_mode','quote_count','amount_cents','real_admin_review_executed','real_quote_api_executed','previous_quote_actions_executed','real_external_side_effects'] as $key){
            if(!array_key_exists($key,$payload)||is_array($payload[$key]))continue;
            $value=$payload[$key];
            $text=is_bool($value)?($value?'是':'否'):($key==='scenario'?self::scenario($value):self::label($value));
            $parts[]=self::label($key).'：'.$text;
        }
        return $parts?implode('；',$parts):'详细数据见技术详情';
    }
