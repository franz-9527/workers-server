    public static function label($value, string $context = ''): string
    {
        $value=(string)$value;
        if($value==='')return '未记录';
        return self::CONTEXTS[$context][$value]??self::LABELS[$value]??$value;
    }

    /** 检查报告中的字段和状态转为中文；未知技术标识保留便于诊断。 */
    public static function fact($value): string
    {
        return (string)preg_replace_callback('/[A-Za-z][A-Za-z0-9_]*/',static function(array $match):string{
            return self::LABELS[$match[0]]??$match[0];
        },(string)$value);
    }

    public static function action($key): string
    {
        $key=(string)$key;
        if(isset(self::ACTIONS[$key]))return self::ACTIONS[$key];
        if(strpos($key,'verify')===0)return '检查测试实例';
        return self::label($key);
    }

    public static function scenario($key): string
    {
        static $names=null;
        if($names===null){
            $names=[];
            foreach((new TestScenarioCatalog())->all() as $row)$names[(string)$row['key']]=(string)$row['name'];
        }
        return $names[(string)$key]??'未收录场景';
    }

