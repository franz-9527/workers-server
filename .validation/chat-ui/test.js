'use strict'
// trigger isolated validation after workflow registration
const assert=require('node:assert/strict')
const fs=require('node:fs')
const f=JSON.parse(fs.readFileSync(__dirname+'/fixture.json','utf8'))
assert.match(f.source_commit,/^[0-9a-f]{40}$/)
assert(!f.inbox_wxml.includes('class="chat-filter"'),'正文不得重复显示状态筛选条')
assert(!f.inbox_wxml.includes('chat-role-filter'),'正文不得重复显示身份筛选条')
assert(f.inbox_wxml.includes('data-action="role_customer"')&&f.inbox_wxml.includes('我的下单'),'下单应是独立菜单项')
assert(f.inbox_wxml.includes('data-action="role_worker"')&&f.inbox_wxml.includes('我的接单'),'接单应是独立菜单项')
assert(f.inbox_wxml.includes('data-action="filter_later"')&&f.inbox_wxml.includes('data-action="filter_ended"'),'状态筛选应保留在菜单')
assert(!f.conversation_wxml.includes('conversation-context-main'),'会话正文不得重复导航标题')
assert(f.conversation_wxml.includes('conversation-context-only'),'会话正文仅保留订单编号/状态辅助信息')
assert(f.conversation_wxml.includes('chat-icon-tune'),'会话菜单入口应保留')
assert.equal(f.conversation_json.homeButton,false,'会话页应关闭原生主页按钮')
assert.equal(f.conversation_json.navigationBarBackgroundColor,'#f7f7f7')
assert(f.inbox_js.includes("&title="),'进入会话时应携带标题，避免原生导航标题闪烁')
assert(f.conversation_js.includes('setNavigationBarTitle'),'会话加载前应立即设置原生导航标题')
console.log('chat ui contract OK',f.source_commit)
