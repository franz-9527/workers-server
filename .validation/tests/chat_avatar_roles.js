'use strict'
const fs=require('fs')
const path=require('path')
const root=path.join(__dirname,'..','source')
const user=fs.readFileSync(path.join(root,'miniprogram/images/chat-user.svg'),'utf8')
const worker=fs.readFileSync(path.join(root,'miniprogram/images/chat-worker.svg'),'utf8')
const identity=fs.readFileSync(path.join(root,'miniprogram/utils/ChatIdentity.js'),'utf8')
function ok(v,m){if(!v)throw Error(m)}
ok(user.includes('viewBox="0 0 64 64"'),'user avatar must restore original 64x64 icon')
ok(user.includes('#3986db'),'user avatar must restore original blue user mark')
ok(!user.includes('壁选'),'user avatar must not be worker brand avatar')
ok(worker.includes('viewBox="0 0 300 300"'),'worker avatar must use vectorized worker source')
ok(worker.includes('#e8f2ff'),'worker avatar must keep local light-blue background')
ok((worker.match(/<path/g)||[]).length>=20,'worker avatar must be vector paths')
ok(!worker.includes('<image')&&!worker.includes('data:image'),'worker avatar must not embed raster')
ok(!worker.includes('tcb.qcloud.la'),'worker avatar must not reference remote source')
ok(identity.includes("user:'/images/chat-user.svg'"),'user identity mapping changed')
ok(identity.includes("worker:'/images/chat-worker.svg'"),'worker identity mapping changed')
console.log('chat avatar role mapping validation: OK')
