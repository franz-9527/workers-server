'use strict'
const fs=require('fs')
const path=require('path')
function check(ok,msg){if(!ok)throw Error(msg)}
const root=path.join(__dirname,'..','source')
const client=fs.readFileSync(path.join(root,'server/assets/chat-testing-client.js'),'utf8')
const runtime=fs.readFileSync(path.join(root,'server/assets/chat-testing-runtime.js'),'utf8')
const view=fs.readFileSync(path.join(root,'server/views/admin/chat-testing.php'),'utf8')
for(const code of ['CALL_unavailable','CALL_exhausted','CALL_safety_insufficient','CALL_disabled'])check(client.includes(code),'missing route code '+code)
check(client.includes("calls.call('availability',{conversation_id:this.cid})"),'source must preflight call availability')
check(client.includes('语音/视频通话仅支持两人会话'),'source must explain direct-only calls')
check(client.includes("data-call-audio]').disabled"),'source must disable unavailable audio call')
check(client.includes("data-call-video]').disabled"),'source must disable unavailable video call')
check(runtime.includes('calls.call("availability", { conversation_id: this.cid })'),'bundle must preflight call availability')
check(runtime.includes('CALL_unavailable'),'bundle must expose sandbox route failures')
check(runtime.includes('当前为多人测试会话；语音/视频通话仅支持两人会话'),'bundle must explain direct-only calls')
check(view.includes('浏览器语音/视频通话仅支持两人测试会话'),'admin view must explain call boundary')
check(view.includes('固定使用声网 Web RTC'),'admin view must explain sandbox provider')
console.log('chat testing call availability contract: OK')
