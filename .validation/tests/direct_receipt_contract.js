'use strict'
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.join(__dirname,'..','source')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const history=read('chat/internal/message/history.go')
const collab=read('chat/internal/message/collaboration.go')
const unread=read('chat/internal/message/unread.go')
const progress=read('chat/internal/message/read_progress.go')
const realtime=read('chat/internal/socket/realtime.go')
const socket=read('chat/internal/dependencies/socket.go')
const manager=read('miniprogram/utils/ChatManager.js')
const index=read('miniprogram/subpackages/chat/conversation/index.js')
const sim=read('server/app/Application/Chat/ChatSimulation.php')
const sandbox=read('server/app/Application/Chat/ChatSandbox.php')
assert.match(history,/PeerReadSeq\s+ports\.ID\s+`json:"peer_read_seq,omitempty"`/)
assert.match(history,/peerReadSeqLocked/)
assert.match(collab,/grant\.Mode != "direct"/)
assert.match(collab,/chat_member_reads/)
assert.match(collab,/len\(candidates\) != 1/)
assert.match(unread,/PeerReadSeq\s+ports\.ID/)
assert.match(progress,/changed && g\.Mode == "direct"/)
assert.match(progress,/ReceiptChanged/)
assert.match(realtime,/kind: "receipt\.changed"/)
assert.match(realtime,/payload\["read_seq"\]/)
assert.match(realtime,/event\.exclude\.Valid\(\)/)
assert.match(socket,/SetReceiptPublisher\(r\.Socket\)/)
assert.match(manager,/f\.type==='receipt\.changed'/)
assert.match(manager,/model\.peerReadSeq/)
assert.match(index,/applyPeerReadSeq/)
assert.match(index,/peer_read_seq/)
assert.match(sim,/peer_read_seq/)
assert.match(sandbox,/peer_read_seq/)
console.log('direct receipt protocol contract: OK')
