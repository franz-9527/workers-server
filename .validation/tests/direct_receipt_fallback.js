'use strict'
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.join(__dirname,'..','source')
const unread=fs.readFileSync(path.join(root,'chat/internal/message/unread.go'),'utf8')
const manager=fs.readFileSync(path.join(root,'miniprogram/utils/ChatManager.js'),'utf8')
const normal=unread.slice(unread.indexOf('func (s *HistoryService) Unread('))
assert.match(normal,/peerReadSeqLocked\(ctx, tx, p, id, g\)/,'normal conversation.unread must include peer watermark')
assert.match(normal,/out\.PeerReadSeq = peer/)
assert.match(manager,/f\.type==='receipt\.changed'/)
assert.match(manager,/model\.peerReadSeq=seq/,'receipt.changed must advance in-memory peer watermark')
assert.match(manager,/compare\(seq,model\.peerReadSeq\)>=0/)
assert.match(manager,/model&&model\.peerReadSeq\?\{read_seq:model\.peerReadSeq\}/)
console.log('direct receipt fallback contract: OK')
