const { chromium } = require('playwright')
const path = require('node:path')
;(async () => {
 const browser = await chromium.launch({headless:true})
 const page = await browser.newPage({viewport:{width:1280,height:900}})
 await page.route(/^https?:/,route=>route.abort())
 await page.goto('file://'+path.resolve('test-artifacts/admin-wecom.html'))
 const test = page.locator('#wecom-test-form button[type=submit]')
 if(!await test.isVisible())throw Error('管理员通知测试按钮不可见')
 const box=await test.boundingBox()
 if(!box||box.y+box.height>900)throw Error('测试按钮没有在首屏显示')
 if(await page.locator('#wecom-test-form form').count())throw Error('嵌套表单')
 await page.screenshot({path:'test-artifacts/admin-wecom.png',fullPage:true})
 await page.goto('file://'+path.resolve('test-artifacts/admin-subscribe.html'))
 if(await page.locator('[data-subscribe-scene-tab]').count()!==3)throw Error('不是三类模板')
 if(!await page.locator('[data-subscribe-scene-panel="order_progress"]').isVisible())throw Error('订单模板未默认显示')
 await page.screenshot({path:'test-artifacts/admin-subscribe.png',fullPage:true})
 await browser.close()
 console.log('浏览器首屏测试按钮与三类模板布局验证通过')
})().catch(error=>{console.error(error);process.exitCode=1})
